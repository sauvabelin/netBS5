<?php

declare(strict_types=1);

namespace App\Tests\MailingBundle;

use Iacopo\MailingBundle\Api\PostfixMapController;
use Iacopo\MailingBundle\Command\ExportPostfixMapCommand;
use Iacopo\MailingBundle\Entity\MailingList;
use Iacopo\MailingBundle\Entity\MailingListAlias;
use Iacopo\MailingBundle\Repository\MailingListRepository;
use Iacopo\MailingBundle\Service\MailingTargetResolver;
use Iacopo\MailingBundle\Service\PostfixVirtualMapBuilder;
use PHPUnit\Framework\TestCase;
use Psr\Log\NullLogger;
use Symfony\Component\Console\Command\Command;
use Symfony\Component\Console\Tester\CommandTester;
use Symfony\Component\HttpFoundation\Request;

class PostfixMapExportTest extends TestCase
{
    public function test_builds_sorted_expanded_map_and_reports_skipped_entries(): void
    {
        $chefs = $this->list(1, 'Chefs', 'Chefs@Sauvabelin.ch', ['cheftaine@sauvabelin.ch']);
        $empty = $this->list(2, 'Vide', 'vide@sauvabelin.ch');
        $loop  = $this->list(3, 'Loop', 'loop@sauvabelin.ch');

        $builder = $this->builder([
            [$chefs, ['zoe@example.com', 'Alice@Example.com', 'alice@example.com', 'bad address@example.com']],
            [$empty, []],
            [$loop, ['loop@sauvabelin.ch', 'bob@example.com']],
        ]);

        $map = $builder->build();

        // Aliases resolve straight to recipients (no hop through the base
        // address); keys and recipients are lowercased, deduplicated, sorted.
        $this->assertSame(
            "# Generated by netbs:mailing:export-postfix. Do not edit by hand.\n"
            . "chefs@sauvabelin.ch\talice@example.com, zoe@example.com\n"
            . "cheftaine@sauvabelin.ch\talice@example.com, zoe@example.com\n"
            . "loop@sauvabelin.ch\tbob@example.com\n",
            $map->render(),
        );

        $warnings = implode("\n", $map->warnings);
        $this->assertStringContainsString('malformed recipient "bad address@example.com"', $warnings);
        $this->assertStringContainsString('vide@sauvabelin.ch has no recipients', $warnings);
        $this->assertStringContainsString('self-reference to loop@sauvabelin.ch', $warnings);
    }

    public function test_command_writes_file_atomically_and_refuses_empty_map(): void
    {
        $dir = sys_get_temp_dir() . '/postfix-export-' . bin2hex(random_bytes(4));
        mkdir($dir);
        $path = $dir . '/virtual';

        try {
            $tester = new CommandTester(new ExportPostfixMapCommand($this->builder([
                [$this->list(1, 'Chefs', 'chefs@sauvabelin.ch'), ['alice@example.com']],
            ])));
            $this->assertSame(Command::SUCCESS, $tester->execute(['--output' => $path]));
            $this->assertStringContainsString("chefs@sauvabelin.ch\talice@example.com\n", file_get_contents($path));
            $this->assertSame(['virtual'], array_values(array_diff(scandir($dir), ['.', '..'])), 'no temp file left behind');

            // A failing/empty DB must not clobber the last good map.
            $tester = new CommandTester(new ExportPostfixMapCommand($this->builder([])));
            $this->assertSame(Command::FAILURE, $tester->execute(['--output' => $path]));
            $this->assertStringContainsString('chefs@sauvabelin.ch', file_get_contents($path));

            $this->assertSame(Command::SUCCESS, $tester->execute(['--output' => $path, '--allow-empty' => true]));
            $this->assertStringNotContainsString('chefs@sauvabelin.ch', file_get_contents($path));
        } finally {
            @unlink($path);
            @rmdir($dir);
        }
    }

    public function test_endpoint_requires_token_and_refuses_empty_map(): void
    {
        $withList = $this->builder([[$this->list(1, 'Chefs', 'chefs@sauvabelin.ch'), ['alice@example.com']]]);
        $request = static fn (?string $auth): Request => Request::create(
            '/mailing-export/postfix-map',
            server: $auth === null ? [] : ['HTTP_AUTHORIZATION' => $auth],
        );

        // No configured token: never serve the address list.
        $this->assertSame(500, (new PostfixMapController($withList, new NullLogger(), ''))($request('Bearer '))->getStatusCode());

        $controller = new PostfixMapController($withList, new NullLogger(), 's3cret');
        $this->assertSame(401, $controller($request(null))->getStatusCode());
        $this->assertSame(401, $controller($request('Bearer wrong'))->getStatusCode());

        $response = $controller($request('Bearer s3cret'));
        $this->assertSame(200, $response->getStatusCode());
        $this->assertSame('1', $response->headers->get('X-Map-Entries'));
        $this->assertStringContainsString("chefs@sauvabelin.ch\talice@example.com\n", $response->getContent());

        // Empty map → 5xx, so the mail node keeps its last good copy.
        $empty = new PostfixMapController($this->builder([]), new NullLogger(), 's3cret');
        $this->assertSame(503, $empty($request('Bearer s3cret'))->getStatusCode());
    }

    /**
     * @param list<array{MailingList, list<string>}> $listsWithRecipients
     */
    private function builder(array $listsWithRecipients): PostfixVirtualMapBuilder
    {
        $repository = $this->createMock(MailingListRepository::class);
        $repository->method('findBy')->with(['active' => true])
            ->willReturn(array_column($listsWithRecipients, 0));

        $resolver = $this->createMock(MailingTargetResolver::class);
        $resolver->method('resolveMailingList')->willReturnCallback(
            function (MailingList $list) use ($listsWithRecipients): array {
                foreach ($listsWithRecipients as [$candidate, $recipients]) {
                    if ($candidate === $list) {
                        return $recipients;
                    }
                }
                return [];
            },
        );

        return new PostfixVirtualMapBuilder($repository, $resolver);
    }

    /**
     * @param list<string> $aliases
     */
    private function list(int $id, string $name, string $baseAddress, array $aliases = []): MailingList
    {
        $list = (new MailingList())->setName($name)->setBaseAddress($baseAddress);
        (new \ReflectionProperty(MailingList::class, 'id'))->setValue($list, $id);
        foreach ($aliases as $address) {
            $list->addAlias((new MailingListAlias())->setAddress($address));
        }

        return $list;
    }
}
