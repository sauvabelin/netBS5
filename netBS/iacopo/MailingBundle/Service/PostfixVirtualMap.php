<?php

declare(strict_types=1);

namespace Iacopo\MailingBundle\Service;

final class PostfixVirtualMap
{
    /**
     * @param array<string, list<string>> $entries  source address => recipients, sorted
     * @param list<string>                $warnings entries skipped or adjusted while building
     */
    public function __construct(
        public readonly array $entries,
        public readonly array $warnings,
    ) {
    }

    /**
     * Render in Postfix lookup-table source format (`key<TAB>value`), sorted so
     * that two exports of the same data are byte-identical and diffable.
     */
    public function render(): string
    {
        $lines = ["# Generated by netbs:mailing:export-postfix. Do not edit by hand."];
        foreach ($this->entries as $source => $recipients) {
            $lines[] = $source . "\t" . implode(', ', $recipients);
        }

        return implode("\n", $lines) . "\n";
    }
}
