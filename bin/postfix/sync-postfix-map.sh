#!/bin/sh
# Pull the mailing-list virtual alias map from netBS and install it for Postfix.
#
# Runs on the mail node from cron (e.g. every 5 minutes). Postfix reads the
# result through:
#     virtual_alias_maps = lmdb:/etc/postfix/netbs_virtual
# and notices the new file on its own; no reload is needed.
#
# Any failure (netBS down, bad token, malformed or suspiciously small map)
# leaves the currently installed map untouched, so mail keeps flowing.
#
# Configuration (environment):
#   NETBS_MAP_URL            full URL of /mailing-export/postfix-map  (required)
#   POSTFIX_MAP_TOKEN        bearer token, or
#   POSTFIX_MAP_TOKEN_FILE   file containing it (preferred: keeps it out of `ps`/crontab)
#   MAP_PATH                 default /etc/postfix/netbs_virtual
#   MAX_DROP_PERCENT         refuse a map that lost more than this % of entries (default 50)
#   FORCE=1                  install even if the drop check fails
set -eu

: "${NETBS_MAP_URL:?NETBS_MAP_URL is required}"
MAP_PATH="${MAP_PATH:-/etc/postfix/netbs_virtual}"
MAX_DROP_PERCENT="${MAX_DROP_PERCENT:-50}"
FORCE="${FORCE:-0}"
HEADER='# Generated by netbs:mailing:export-postfix. Do not edit by hand.'

if [ -n "${POSTFIX_MAP_TOKEN_FILE:-}" ]; then
    POSTFIX_MAP_TOKEN=$(cat "$POSTFIX_MAP_TOKEN_FILE")
fi
: "${POSTFIX_MAP_TOKEN:?POSTFIX_MAP_TOKEN or POSTFIX_MAP_TOKEN_FILE is required}"

fail() { echo "sync-postfix-map: $*" >&2; exit 1; }

# Stage next to the target so the final mv is an atomic rename.
tmp=$(mktemp -d "$(dirname "$MAP_PATH")/.netbs_virtual.XXXXXX")
trap 'rm -rf "$tmp"' EXIT

# The token goes through a curl config on stdin so it never shows up in argv.
printf 'header = "Authorization: Bearer %s"\n' "$POSTFIX_MAP_TOKEN" \
    | curl --config - -fsS --max-time 30 -o "$tmp/map" "$NETBS_MAP_URL" \
    || fail "download from $NETBS_MAP_URL failed; keeping current map"

[ "$(head -n 1 "$tmp/map")" = "$HEADER" ] || fail "unexpected content (missing header); keeping current map"

new_count=$(grep -cv '^#' "$tmp/map" || true)
[ "$new_count" -gt 0 ] || fail "map has no entries; keeping current map"

if [ -f "$MAP_PATH" ]; then
    cmp -s "$tmp/map" "$MAP_PATH" && exit 0

    old_count=$(grep -cv '^#' "$MAP_PATH" || true)
    if [ "$FORCE" != 1 ] && [ $((new_count * 100)) -lt $((old_count * (100 - MAX_DROP_PERCENT))) ]; then
        fail "entries dropped from $old_count to $new_count (> ${MAX_DROP_PERCENT}%); keeping current map, rerun with FORCE=1 if intended"
    fi
fi

chmod 0644 "$tmp/map"
postmap "lmdb:$tmp/map" || fail "postmap rejected the map; keeping current map"

# Database first: it is what Postfix reads. The text file is kept alongside
# for diffing and for the next run's change/drop checks.
mv -f "$tmp/map.lmdb" "$MAP_PATH.lmdb"
mv -f "$tmp/map" "$MAP_PATH"

echo "sync-postfix-map: installed $new_count addresses (was ${old_count:-none})"
